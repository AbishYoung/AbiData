// pgTestMigrate stands in for catalog.MigratePostgres: the writer row and one table.
func pgTestMigrate(ctx context.Context, _ ids.WorkspaceID, d dbx.Execer, n pgdb.Names) error {
	s := pgdb.Ident(n.Schema())
	_, err := d.Exec(ctx, `CREATE TABLE IF NOT EXISTS `+s+`._sys_schema (id integer PRIMARY KEY, application_id bigint NOT NULL, version integer NOT NULL);
		INSERT INTO `+s+`._sys_schema VALUES (1, 0, 1) ON CONFLICT DO NOTHING;
		CREATE TABLE IF NOT EXISTS `+s+`.t (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v bigint NOT NULL DEFAULT 0)`)
	return err
}

type pgMgr struct {
	*Manager
	e *pgtest.Env
}

func newPGMgr(t *testing.T, migrate func(context.Context, ids.WorkspaceID, dbx.Execer, pgdb.Names) error) pgMgr {
	t.Helper()
	e := pgtest.New(t)
	if err := pgdb.InstallLib(context.Background(), pgdb.Pool(e.App), pgdb.Names{Prefix: e.Prefix}); err != nil {
		t.Fatal(err)
	}
	m, err := NewManager(Config{DataDir: t.TempDir(), MaxOpen: 4, GateTimeout: 300 * time.Millisecond,
		Postgres: &PostgresConfig{Pool: e.App, Database: e.Database, Prefix: e.Prefix, Migrate: migrate}})
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = m.Shutdown(context.Background()) })
	return pgMgr{m, e}
}

func (m pgMgr) create(t *testing.T) ids.WorkspaceID {
	t.Helper()
	id := ids.NewWorkspaceID()
	n := m.Names(id)
	m.e.DropRoles(n.ReadLogin(), n.WriteLogin(), n.WriteRole(), n.ReadRole())
	if err := m.Create(context.Background(), id); err != nil {
		t.Fatal(err)
	}
	return id
}

func TestPostgresCreateReadWrite(t *testing.T) {
	m := newPGMgr(t, pgTestMigrate)
	ctx := context.Background()
	if _, err := m.Acquire(ctx, ids.NewWorkspaceID()); !errors.Is(err, ErrNotExist) {
		t.Fatalf("missing workspace: %v", err)
	}
	id := m.create(t)
	if err := m.Create(ctx, id); !errors.Is(err, fs.ErrExist) {
		t.Fatalf("second Create: %v", err)
	}
	l, err := m.Acquire(ctx, id)
	if err != nil {
		t.Fatal(err)
	}
	defer l.Release()
	if err := l.Write(ctx, Interactive, func(tx dbx.Tx) error {
		_, err := tx.Exec(ctx, `INSERT INTO t (v) VALUES (?)`, 7)
		return err
	}); err != nil {
		t.Fatal(err)
	}
	var v int64
	if err := l.Read(ctx, func(q dbx.Querier) error { return q.QueryRow(ctx, `SELECT v FROM t`).Scan(&v) }); err != nil || v != 7 {
		t.Fatalf("read %d, %v", v, err)
	}
	err = l.Read(ctx, func(q dbx.Querier) error {
		_, err := q.(dbx.Execer).Exec(ctx, `INSERT INTO t (v) VALUES (1)`)
		return err
	})
	if err == nil {
		t.Fatal("a write inside Read succeeded")
	}
	if err := l.Write(ctx, Interactive, func(tx dbx.Tx) error {
		if err := l.Write(ctx, Interactive, func(dbx.Tx) error { return nil }); !errors.Is(err, ErrNestedWrite) {
			t.Errorf("nested write: %v", err)
		}
		return nil
	}); err != nil {
		t.Fatal(err)
	}

	// The search path was SET LOCAL: a connection back in the pool has the default.
	var path string
	if err := m.e.App.QueryRow(ctx, `SHOW search_path`).Scan(&path); err != nil || path != `"$user", public` {
		t.Errorf("pooled connection's search_path %q, %v", path, err)
	}

	for name, err := range map[string]error{
		"ReadConn":    l.ReadConn(ctx, func(*sqlitex.Conn) error { return nil }),
		"Maintenance": l.Maintenance(ctx, func(*sqlitex.Conn) error { return nil }),
		"Exclusive":   l.Exclusive(ctx, time.Second, func(Paths) error { return nil }),
		"WriteWith":   l.WriteWith(ctx, Interactive, WriteOptions{ForeignKeysOff: true}, func(dbx.Tx) error { return nil }),
	} {
		if !errors.Is(err, ErrSQLiteOnly) {
			t.Errorf("%s: %v", name, err)
		}
	}
}

// TestPostgresWritesSerialise: concurrent read-modify-write transactions lose nothing.
func TestPostgresWritesSerialise(t *testing.T) {
	m := newPGMgr(t, pgTestMigrate)
	ctx := context.Background()
	id := m.create(t)
	l, err := m.Acquire(ctx, id)
	if err != nil {
		t.Fatal(err)
	}
	defer l.Release()
	if err := l.Write(ctx, Background, func(tx dbx.Tx) error {
		_, err := tx.Exec(ctx, `INSERT INTO t (id, v) VALUES (1, 0)`)
		return err
	}); err != nil {
		t.Fatal(err)
	}
	var wg sync.WaitGroup
	for range 16 {
		wg.Go(func() {
			l, err := m.Acquire(ctx, id)
			if err != nil {
				t.Error(err)
				return
			}
			defer l.Release()
			if err := l.Write(ctx, Background, func(tx dbx.Tx) error {
				var v int64
				if err := tx.QueryRow(ctx, `SELECT v FROM t WHERE id = 1`).Scan(&v); err != nil {
					return err
				}
				_, err := tx.Exec(ctx, `UPDATE t SET v = ? WHERE id = 1`, v+1)
				return err
			}); err != nil {
				t.Error(err)
			}
		})
	}
	wg.Wait()
	var v int64
	if err := l.Read(ctx, func(q dbx.Querier) error { return q.QueryRow(ctx, `SELECT v FROM t WHERE id = 1`).Scan(&v) }); err != nil || v != 16 {
		t.Fatalf("v = %d, %v", v, err)
	}
}

// TestPostgresWriterRowBusy: a connection holding the writer row (another
// instance, say) makes an interactive write fail with WORKSPACE_BUSY.
func TestPostgresWriterRowBusy(t *testing.T) {
	m := newPGMgr(t, pgTestMigrate)
	ctx := context.Background()
	id := m.create(t)
	tx, err := m.e.App.Begin(ctx)
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = tx.Rollback(ctx) }()
	if _, err := tx.Exec(ctx, `SELECT 1 FROM `+pgdb.Ident(m.Names(id).Schema())+`._sys_schema FOR UPDATE`); err != nil {
		t.Fatal(err)
	}
	l, err := m.Acquire(ctx, id)
	if err != nil {
		t.Fatal(err)
	}
	defer l.Release()
	err = l.Write(ctx, Interactive, func(dbx.Tx) error { return nil })
	var fe *fault.Error
	if !errors.As(err, &fe) || fe.Code != fault.WorkspaceBusy {
		t.Fatalf("want WORKSPACE_BUSY, got %v", err)
	}
}

// TestPostgresCreateRollsBack: a failed migration leaves no schema or roles.
func TestPostgresCreateRollsBack(t *testing.T) {
	fail := true
	m := newPGMgr(t, func(ctx context.Context, id ids.WorkspaceID, d dbx.Execer, n pgdb.Names) error {
		if fail {
			return errors.New("boom")
		}
		return pgTestMigrate(ctx, id, d, n)
	})
	ctx := context.Background()
	id := ids.NewWorkspaceID()
	n := m.Names(id)
	m.e.DropRoles(n.ReadLogin(), n.WriteLogin(), n.WriteRole(), n.ReadRole())
	if err := m.Create(ctx, id); err == nil {
		t.Fatal("Create succeeded")
	}
	var objects int
	if err := m.e.App.QueryRow(ctx, `SELECT (SELECT count(*) FROM pg_namespace WHERE nspname = $1) +
		(SELECT count(*) FROM pg_roles WHERE rolname LIKE $1 || '%')`, n.Schema()).Scan(&objects); err != nil || objects != 0 {
		t.Fatalf("%d objects left, %v", objects, err)
	}
	fail = false
	if err := m.Create(ctx, id); err != nil {
		t.Fatal(err)
	}
}

func TestPostgresDrop(t *testing.T) {
	m := newPGMgr(t, pgTestMigrate)
	ctx := context.Background()
	id := m.create(t)
	l, err := m.Acquire(ctx, id)
	if err != nil {
		t.Fatal(err)
	}
	if err := m.Drop(ctx, id); err == nil {
		t.Fatal("dropped an open workspace")
	}
	l.Release()
	m.CloseIdle(ctx, 0)
	deadline := time.Now().Add(5 * time.Second)
	for m.Open() > 0 && time.Now().Before(deadline) {
		time.Sleep(10 * time.Millisecond)
	}
	if err := m.Drop(ctx, id); err != nil {
		t.Fatal(err)
	}
	if _, err := m.Acquire(ctx, id); !errors.Is(err, ErrNotExist) {
		t.Fatalf("after Drop: %v", err)
	}
	n := m.Names(id)
	var roles int
	if err := m.e.App.QueryRow(ctx, `SELECT count(*) FROM pg_roles WHERE rolname LIKE $1 || '%'`, n.Schema()).Scan(&roles); err != nil || roles != 0 {
		t.Fatalf("%d roles left, %v", roles, err)
	}
}

// TestPostgresStatementsKeyedBySchema: the same statement text in two
// workspaces whose tables differ, and in one workspace before and after a
// type change, must not reuse a prepared statement whose result type no
// longer fits ("cached plan must not change result type").
func TestPostgresStatementsKeyedBySchema(t *testing.T) {
	m := newPGMgr(t, pgTestMigrate)
	ctx := context.Background()
	a, b := m.create(t), m.create(t)
	lease := func(id ids.WorkspaceID) *Lease {
		l, err := m.Acquire(ctx, id)
		if err != nil {
			t.Fatal(err)
		}
		t.Cleanup(l.Release)
		return l
	}
	la, lb := lease(a), lease(b)
	write := func(l *Lease, schemaChange bool, sql string) {
		t.Helper()
		if err := l.WriteWith(ctx, Interactive, WriteOptions{SchemaChange: schemaChange}, func(tx dbx.Tx) error {
			_, err := tx.Exec(ctx, sql)
			return err
		}); err != nil {
			t.Fatal(err)
		}
	}
	write(la, true, `CREATE TABLE u (x bigint); INSERT INTO u VALUES (1)`)
	write(lb, true, `CREATE TABLE u (x text); INSERT INTO u VALUES ('one')`)
	read := func(l *Lease) any {
		t.Helper()
		var v any
		// Several times, so the statement is cached on whichever connections serve it.
		for range 3 {
			if err := l.Read(ctx, func(q dbx.Querier) error {
				rows, err := q.Query(ctx, `SELECT x FROM u WHERE x IS NOT NULL`, nil...)
				if err != nil {
					return err
				}
				defer rows.Close()
				for rows.Next() {
					v = rows.Values()[0]
				}
				return rows.Err()
			}); err != nil {
				t.Fatal(err)
			}
		}
		return v
	}
	if va, vb := read(la), read(lb); va != int64(1) || vb != "one" {
		t.Fatalf("a %v, b %v", va, vb)
	}
	write(la, true, `ALTER TABLE u ALTER COLUMN x TYPE text`)
	if va := read(la); va != "1" {
		t.Fatalf("after the type change: %v", va)
	}
}
