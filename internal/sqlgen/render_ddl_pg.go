package sqlgen

import (
	"fmt"
	"regexp"
	"strings"
)

// usesLib finds a call of a <prefix>_lib function in rendered SQL. A text
// literal that happens to match only makes a column STORED, which is safe.
var usesLib = regexp.MustCompile(`\b(abi_|geo_)\w*\(`)

// PostgreSQL DDL (ADR 0013 Phase F, ADR 0012 §4). Columns get native storage
// types; text is binary ("C") as on SQLite, and abi_ci is applied where SQLite
// says NOCASE. Stored expressions (generated columns, defaults, checks) are
// rendered by the PostgreSQL expression renderer; a generated column's
// expression must be IMMUTABLE there, which the <prefix>_lib functions are.

// pgStorageType is the column type of a logical type on PostgreSQL.
func pgStorageType(t Type) string {
	switch t {
	case Integer, Currency:
		return "bigint"
	case Number:
		return "double precision"
	case Boolean:
		return "boolean"
	case Date:
		return "date"
	case DateTime:
		return "timestamptz"
	case JSON, GeoPoint, GeoArea, Attachments:
		return "jsonb"
	}
	return `text COLLATE "C"`
}

func (r *renderer) pgColumnDef(q string, c ColumnDef) {
	if c.AutoIncrement {
		// BY DEFAULT rather than ALWAYS: restore and import write rows with
		// their IDs. An identity never reuses a value, like AUTOINCREMENT.
		r.w("bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
		return
	}
	if c.Generated != nil {
		if c.Default != nil || c.NotNull || len(c.Checks) > 0 {
			r.fail("generated column %s takes no default, NOT NULL or checks", c.Name)
		}
		// VIRTUAL needs PostgreSQL 18 and may call builtins only; an
		// expression that uses <prefix>_lib is STORED (computed on write).
		sub := &renderer{d: r.d, seen: map[string]bool{}}
		sub.pgStored(c.Generated, c.Type)
		if sub.err != nil {
			r.fail("%v", sub.err)
			return
		}
		r.w(pgStorageType(c.Type) + " GENERATED ALWAYS AS (" + sub.b.String())
		if r.d == Postgres17 || usesLib.MatchString(sub.b.String()) {
			r.w(") STORED")
		} else {
			r.w(") VIRTUAL")
		}
		return
	}
	r.w(pgStorageType(c.Type))
	if c.NotNull {
		r.w(" NOT NULL")
	}
	if c.Default != nil {
		r.w(" DEFAULT (")
		r.pgStored(c.Default, c.Type)
		r.w(")")
	}
	if dc := pgDomainCheck(q, c); dc != "" {
		if c.TypeCheck == "" {
			r.fail("column %s needs a name for its type check", c.Name)
		}
		r.w(" CONSTRAINT " + Quote(c.TypeCheck) + " CHECK (" + dc + ")")
	}
	for _, ck := range c.Checks {
		r.need(ck.Name)
		r.w(" CONSTRAINT " + Quote(ck.Name) + " CHECK (")
		r.pgCondition(ck.Expr)
		r.w(")")
	}
}

// pgStored renders a generated column's expression or a default as a value
// of the column's storage type. SQLite stores whatever the expression gives in
// a column of affinity; PostgreSQL needs the type, so date and time text goes
// through SQLite's parser, numbers become yes/no as non-zero, and so on.
func (r *renderer) pgStored(e Expr, t Type) {
	from := typeOf(e)
	if l, ok := e.(Lit); ok {
		switch {
		case t == Boolean:
			e = Lit{Value: l.Value, Type: Boolean}
		case t == Integer || t == Currency || t == Number || l.Value == nil:
		default:
			// A text literal is an unknown-typed constant PostgreSQL reads as
			// the column's type (a date, a timestamp, JSON).
			r.expr(e)
			return
		}
		r.expr(e)
		return
	}
	switch t {
	case Date:
		if pgNativeTime(e) && from == Date {
			r.expr(e)
			return
		}
		r.w("abi_to_date(")
		r.pgText(e)
		r.w(")")
	case DateTime:
		if pgNativeTime(e) && from == DateTime {
			r.expr(e)
			return
		}
		r.w("abi_to_timestamptz(")
		r.pgText(e)
		r.w(")")
	case Boolean:
		if from == Boolean {
			r.expr(e)
			return
		}
		r.operand(e)
		r.w(" <> 0")
	case Integer, Currency:
		if from == Integer || from == Currency {
			r.expr(e)
			return
		}
		r.pgCast(Cast{X: e, Type: t})
	case Number:
		if from == Number {
			r.expr(e)
			return
		}
		r.w("CAST(")
		r.pgNumberExpr(e)
		r.w(" AS double precision)")
	case JSON, GeoPoint, GeoArea, Attachments:
		if pgJSONB(e) {
			r.expr(e)
			return
		}
		r.w("CAST(")
		r.pgText(e)
		r.w(" AS jsonb)")
	case Text:
		r.pgText(e)
	default:
		r.expr(e)
	}
}

// pgDomainCheck is the CHECK that keeps a column's values in its type's domain
// on PostgreSQL. Native types (yes/no, dates) need none.
func pgDomainCheck(q string, c ColumnDef) string {
	switch c.Type {
	case Text:
		switch {
		case c.MaxLen > 0:
			return fmt.Sprintf("char_length(%s) <= %d", q, c.MaxLen)
		case c.URL:
			// GLOB 'http*://*' on SQLite: case-sensitive, anchored at the start.
			return fmt.Sprintf("%s IS NULL OR %s ~ '^http.*://'", q, q)
		}
	case Attachments:
		return fmt.Sprintf("%s IS NULL OR jsonb_typeof(%s) = 'array'", q, q)
	case GeoPoint, GeoArea:
		types := "'Point'"
		if c.Type == GeoArea {
			types = "'Polygon','MultiPolygon'"
		}
		return fmt.Sprintf("%s IS NULL OR (%s ->> 'type') IN (%s)", q, q, types)
	}
	return ""
}

// pgAttachmentRefs renders the trigger for one row event as a call of
// <prefix>_lib's abi_att_refs with the table's and columns' catalog IDs.
func (r *renderer) pgAttachmentRefs(s *AttachmentRefs) {
	lit := func(v string) string {
		l, err := literal(v)
		if err != nil {
			r.fail("%v", err)
		}
		return l
	}
	args := []string{lit(s.TableID)}
	for _, c := range s.Columns {
		args = append(args, lit(c.ID), lit(c.Name))
	}
	t := Quote(s.Table)
	switch s.Event {
	case OnInsert:
		r.w(`CREATE TRIGGER ` + Quote(s.Name) + ` AFTER INSERT ON ` + t)
	case OnUpdate:
		r.w(`CREATE TRIGGER ` + Quote(s.Name) + ` AFTER UPDATE OF `)
		r.list(len(s.Columns), ", ", func(i int) { r.w(Quote(s.Columns[i].Name)) })
		r.w(` ON ` + t)
	case OnDelete:
		r.w(`CREATE TRIGGER ` + Quote(s.Name) + ` AFTER DELETE ON ` + t)
		args = args[:1]
	default:
		r.fail("unknown trigger event %d", s.Event)
		return
	}
	r.w(` FOR EACH ROW EXECUTE FUNCTION abi_att_refs(` + strings.Join(args, ", ") + `)`)
}
