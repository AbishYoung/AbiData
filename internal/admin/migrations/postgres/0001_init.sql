-- Admin schema v1 on PostgreSQL (ADR 0012 §4). The same tables, columns and
-- column types as SQLite's: timestamps are text 'YYYY-MM-DDTHH:MM:SS.sssZ'
-- UTC and flags 0/1 integers, so the statements are the same on both.
-- NOCASE becomes <prefix>_lib's abi_ci; json_valid its abi_json_valid.
CREATE TABLE _adm_users (
  id text COLLATE "C" PRIMARY KEY,
  email text COLLATE @lib.abi_ci NOT NULL UNIQUE,
  display_name text COLLATE "C" NOT NULL,
  password_hash text COLLATE "C" NOT NULL,
  is_platform_admin bigint NOT NULL DEFAULT 0 CHECK (is_platform_admin IN (0,1)),
  disabled bigint NOT NULL DEFAULT 0 CHECK (disabled IN (0,1)),
  created_at text COLLATE "C" NOT NULL,
  last_login_at text COLLATE "C"
);

CREATE TABLE _adm_sessions (
  id_hash text COLLATE "C" PRIMARY KEY,
  user_id text COLLATE "C" NOT NULL REFERENCES _adm_users(id) ON DELETE CASCADE,
  csrf_token text COLLATE "C" NOT NULL,
  created_at text COLLATE "C" NOT NULL,
  last_seen_at text COLLATE "C" NOT NULL,
  expires_at text COLLATE "C" NOT NULL,
  ip text COLLATE "C" NOT NULL DEFAULT '',
  user_agent text COLLATE "C" NOT NULL DEFAULT ''
);
CREATE INDEX _adm_sessions_user ON _adm_sessions(user_id);

CREATE TABLE _adm_login_attempts (
  key text COLLATE "C" PRIMARY KEY,
  count bigint NOT NULL,
  window_start text COLLATE "C" NOT NULL
);

CREATE TABLE _adm_workspaces (
  id text COLLATE "C" PRIMARY KEY,
  name text COLLATE @lib.abi_ci NOT NULL UNIQUE,
  status text COLLATE "C" NOT NULL CHECK (status IN ('active','suspended','restoring','needs_repair','deleted')),
  quota_json text COLLATE "C" NOT NULL DEFAULT '{}' CHECK (@lib.abi_json_valid(quota_json)),
  created_at text COLLATE "C" NOT NULL,
  created_by text COLLATE "C" NOT NULL
);

CREATE TABLE _adm_memberships (
  workspace_id text COLLATE "C" NOT NULL REFERENCES _adm_workspaces(id) ON DELETE CASCADE,
  user_id text COLLATE "C" NOT NULL REFERENCES _adm_users(id) ON DELETE CASCADE,
  role text COLLATE "C" NOT NULL CHECK (role IN ('owner','builder','editor','viewer')),
  PRIMARY KEY (workspace_id, user_id)
);
CREATE INDEX _adm_memberships_user ON _adm_memberships(user_id);

CREATE TABLE _adm_job_index (
  workspace_id text COLLATE "C" NOT NULL,
  job_id text COLLATE "C" NOT NULL,
  next_run_at text COLLATE "C",
  enabled bigint NOT NULL DEFAULT 1 CHECK (enabled IN (0,1)),
  running_run_id text COLLATE "C",
  last_status text COLLATE "C",
  PRIMARY KEY (workspace_id, job_id)
);
CREATE INDEX _adm_job_index_next ON _adm_job_index(next_run_at) WHERE enabled = 1;

CREATE TABLE _adm_backups (
  id text COLLATE "C" PRIMARY KEY,
  workspace_id text COLLATE "C" NOT NULL,
  kind text COLLATE "C" NOT NULL CHECK (kind IN ('manual','scheduled','restore_point','pre_restore')),
  path text COLLATE "C" NOT NULL,
  raw_bytes bigint NOT NULL,
  gz_bytes bigint NOT NULL,
  sha256_gz text COLLATE "C" NOT NULL,
  created_at text COLLATE "C" NOT NULL,
  created_by text COLLATE "C" NOT NULL,
  manifest_json text COLLATE "C" NOT NULL CHECK (@lib.abi_json_valid(manifest_json))
);
CREATE INDEX _adm_backups_ws ON _adm_backups(workspace_id, created_at DESC);

CREATE TABLE _adm_settings (key text COLLATE "C" PRIMARY KEY, value text COLLATE "C" NOT NULL);

CREATE TABLE _adm_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at text COLLATE "C" NOT NULL,
  user_id text COLLATE "C",
  action text COLLATE "C" NOT NULL,
  object_kind text COLLATE "C",
  object_id text COLLATE "C",
  details text COLLATE "C" CHECK (details IS NULL OR @lib.abi_json_valid(details))
);
